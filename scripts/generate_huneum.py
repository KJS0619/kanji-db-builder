def build_complete_huneum():
    """2,136자 전체에 대한 한국어 훈음 데이터 생성"""

    # 기존 korean_huneum.json 로드
    project_root = Path(__file__).parent.parent
    existing_path = project_root / "data" / "raw" / "korean_huneum.json"

    existing_data = {}
    if existing_path.exists():
        with open(existing_path, 'r', encoding='utf-8') as f:
            existing_data = json.load(f)

    # 신자체 → 정자체 변환 후 훈음 조회를 위한 역매핑
    traditional_to_huneum = {}
    for trad, huneum in KOREAN_HUNEUM.items():
        traditional_to_huneum[trad] = huneum

    # 신자체에 대한 훈음도 정자체와 동일하게 매핑
    for shinjitai, traditional in SHINJITAI_TO_TRADITIONAL.items():
        if traditional in KOREAN_HUNEUM:
            traditional_to_huneum[shinjitai] = KOREAN_HUNEUM[traditional]

    # 최종 데이터: 내장 사전 + 기존 데이터 결합
    final_data = {}

    # 1. 내장 사전 우선
    final_data.update(KOREAN_HUNEUM)

    # 2. 신자체 매핑 추가
    final_data.update(traditional_to_huneum)

    # 3. 기존 데이터에서 누락된 항목 보충
    for kanji, huneum in existing_data.items():
        if kanji not in final_data:
            final_data[kanji] = huneum

    return final_data


def save_huneum_data():
    """훈음 데이터를 JSON으로 저장"""
    project_root = Path(__file__).parent.parent
    output_path = project_root / "data" / "raw" / "korean_huneum.json"

    huneum_data = build_complete_huneum()

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(huneum_data, f, ensure_ascii=False, indent=2)

    print(f"한국어 훈음 데이터 저장 완료: {output_path}")
    print(f"총 {len(huneum_data)}자 매핑")

    return huneum_data


if __name__ == "__main__":
    save_huneum_data()
