def load_kanji_master(path):
    """kanji_master.json에서 읽기 정보 로드"""
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    kanji_dict = {}
    for k in data['kanji']:
        kanji_dict[k['literal']] = {
            'korean_hun_eum': k.get('korean_hun_eum', ''),
            'ja_on': k.get('ja_on', []),
            'ja_kun': k.get('ja_kun', []),
        }
    return kanji_dict


def main():
    # 현재 스크립트 위치 기준
    script_dir = os.path.dirname(os.path.abspath(__file__))
    kanji_master_path = os.path.join(script_dir, '..', 'web', 'public', 'data', 'kanji_master.json')
    output_path = os.path.join(script_dir, '..', 'web', 'public', 'data', 'kanji_diff_full.json')

    # kanji_master.json 로드
    print("Loading kanji_master.json...")
    kanji_dict = load_kanji_master(kanji_master_path)
    print(f"Loaded {len(kanji_dict)} kanji from master file")

    # 결과 리스트
    diff_list = []
    id_counter = 1

    print("Processing Traditional → Shinjitai mappings...")

    # 정자체 → 신자체 매핑 처리
    for trad, simp in TRADITIONAL_TO_SHINJITAI.items():
        # 자형이 다른 경우만 포함
        if trad != simp:
            # 신자체가 kanji_master에 있는지 확인 (상용한자인지)
            if simp in kanji_dict:
                info = kanji_dict[simp]

                # 한국 한자음 (정자체 기준 또는 신자체 기준)
                kr_sound = info.get('korean_hun_eum', '')
                if not kr_sound and trad in kanji_dict:
                    kr_sound = kanji_dict[trad].get('korean_hun_eum', '')

                diff_entry = {
                    "id": str(id_counter).zfill(3),
                    "krTraditional": trad,
                    "jpShinjitai": simp,
                    "krSound": kr_sound,
                    "jpOn": ", ".join(info.get('ja_on', [])),
                    "jpKun": ", ".join(info.get('ja_kun', [])),
                    "diffCategory": categorize_diff(trad, simp)
                }
                diff_list.append(diff_entry)
                id_counter += 1

    # 중복 제거 (krTraditional 기준)
    seen = set()
    unique_list = []
    for item in diff_list:
        if item['krTraditional'] not in seen:
            seen.add(item['krTraditional'])
            unique_list.append(item)

    # ID 재정렬
    for i, item in enumerate(unique_list, 1):
        item['id'] = str(i).zfill(3)

    # 결과 저장
    result = {
        "version": "1.0.0",
        "description": "한국 정자체(正字體) ↔ 일본 신자체(新字體) 차이 한자 목록",
        "total_count": len(unique_list),
        "source": "일본 상용한자표(常用漢字表) 신구자체 대조",
        "kanji": unique_list
    }

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(result, f, ensure_ascii=False, indent=2)

    print(f"\nGenerated {len(unique_list)} kanji diff entries")
    print(f"Output saved to: {output_path}")

    # 샘플 출력
    print("\nSample entries:")
    for item in unique_list[:5]:
        print(f"  {item['krTraditional']} → {item['jpShinjitai']} ({item['krSound']}) - {item['diffCategory']}")


if __name__ == "__main__":
    main()
